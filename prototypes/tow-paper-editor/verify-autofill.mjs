import { createRequire } from 'node:module';
import process from 'node:process';
import console from 'node:console';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.PLAYWRIGHT_PACKAGE || 'playwright');
const browser=await chromium.launch({channel:'msedge',headless:true});
const admin=await browser.newContext({viewport:{width:1440,height:1000}});
const member=await browser.newContext();
const ordinaryAdmin=await browser.newContext();
const base='http://127.0.0.1:8080';
let userId,towId,ordinaryAdminId;
try {
  await admin.request.post(base+'/api/auth/login',{data:{username:'preview',password:'local-preview-only'}});
  const username=`autofill-ui-${Date.now()}`;
  const user=await (await admin.request.post(base+'/api/users',{data:{username,password:'test-only'}})).json(); userId=user.id;
  const ordinaryUsername=`ordinary-admin-ui-${Date.now()}`;
  const ordinary=await (await admin.request.post(base+'/api/users',{data:{username:ordinaryUsername,password:'test-only',role:'admin'}})).json(); ordinaryAdminId=ordinary.id;
  await ordinaryAdmin.request.post(base+'/api/auth/login',{data:{username:ordinaryUsername,password:'test-only'}});
  const ordinaryPage=await ordinaryAdmin.newPage(); await ordinaryPage.goto(base);
  await ordinaryPage.getByRole('button',{name:'Users',exact:true}).click();
  await ordinaryPage.getByText(ordinaryUsername,{exact:true}).waitFor();
  assert.equal(await ordinaryPage.getByRole('checkbox',{name:/Autofill/}).count(),0);
  assert.equal(await ordinaryPage.getByRole('button',{name:'Backup',exact:true}).count(),0);
  const hiddenUsers=await (await ordinaryAdmin.request.get(base+'/api/users')).json();
  assert.ok(hiddenUsers.every(user=>!Object.hasOwn(user,'autofill')));
  assert.equal((await ordinaryAdmin.request.put(`${base}/api/users/${userId}`,{data:{autofill:true}})).status(),403);
  const tow=await (await admin.request.post(base+'/api/tows',{data:{airline:'MX',aircraftType:'A220-300',tailNumber:'NAUTOTEST',gate:'Gate 1',towSpot:'NL614'}})).json(); towId=tow.id;
  await member.request.post(base+'/api/auth/login',{data:{username,password:'test-only'}});
  const paper=await member.newPage();
  await paper.goto(`${base}/api/paper-editor/?tow=${towId}`);
  await paper.waitForFunction(()=>!globalThis.document.getElementById('save').disabled);
  assert.equal(await paper.getByRole('button',{name:'CHECKLIST',exact:true}).count(),0);
  assert.equal((await member.request.post(`${base}/api/tows/${towId}/paper-draft/autofill`,{data:{revision:0}})).status(),403);
  const main=await admin.newPage(); await main.goto(base);
  await main.getByRole('button',{name:'Users',exact:true}).click();
  await main.getByLabel(`${username} Autofill`,{exact:true}).click();
  await main.waitForFunction(async(id)=>{const response=await globalThis.fetch('/api/users'); const users=await response.json(); return users.find(user=>user.id===id)?.autofill===true;},userId);
  await main.screenshot({path:'tmp/pdf-review/autofill-account.png',fullPage:true});
  await paper.reload(); await paper.waitForFunction(()=>!globalThis.document.getElementById('save').disabled);
  await paper.setViewportSize({width:390,height:844});
  assert.equal(await paper.locator('#paper-sidebar').isVisible(),false);
  await paper.getByRole('button',{name:'Risk & Checklist',exact:true}).click();
  await paper.getByRole('button',{name:'CHECKLIST',exact:true}).click();
  await paper.getByText('Blank checklist items autofilled and saved',{exact:true}).waitFor();
  const draft=await (await member.request.get(`${base}/api/tows/${towId}/paper-draft`)).json();
  assert.equal(Object.keys(draft.state.answers).length,25);
  assert.equal(draft.state.text.undefined_11,'N/A'); assert.equal(draft.state.text.undefined_44,'N/A - No bypass pin');
  assert.equal(draft.state.text.undefined_26,'In Pushback');
  assert.equal(draft.state.text.Airline,'MX');
  assert.deepEqual(draft.state.risk,{'Tow from':'green','Tow to':'green','Final agreed status':'green'});
  await paper.getByRole('button',{name:'TTWS & Preparation',exact:true}).click();
  await paper.screenshot({path:'tmp/pdf-review/autofill-editor.png',fullPage:true});
  await main.getByLabel(`${username} Autofill`,{exact:true}).click();
  await main.waitForFunction(async(id)=>{const response=await globalThis.fetch('/api/users'); const users=await response.json(); return users.find(user=>user.id===id)?.autofill===false;},userId);
  await paper.getByRole('button',{name:'CHECKLIST',exact:true}).click();
  await paper.getByText('Autofill permission required.',{exact:true}).waitFor();
  assert.equal(await paper.getByRole('button',{name:'CHECKLIST',exact:true}).count(),0);
  console.log('Local administrator controls, ordinary admin restrictions, hidden trigger, A220 defaults, and immediate revocation passed.');
}finally{
  if(towId){await admin.request.delete(`${base}/api/tows/${towId}`,{data:{reason:'Autofill UI test cleanup'}});await admin.request.delete(`${base}/api/tows/${towId}/permanent`);}
  if(userId)await admin.request.delete(`${base}/api/users/${userId}`);
  if(ordinaryAdminId)await admin.request.delete(`${base}/api/users/${ordinaryAdminId}`);
  await browser.close();
}
