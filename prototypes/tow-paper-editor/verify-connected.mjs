import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import process from 'node:process';
import console from 'node:console';
import fs from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || 'playwright');
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const base = 'http://127.0.0.1:8080';
let towId;
const first = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
try {
  for (const asset of ['/api/paper-editor/', '/api/paper-editor/assets/template.js']) {
    assert.equal((await first.request.get(base + asset)).status(), 401);
  }
  const login = {username:'preview',password:'local-preview-only'};
  assert.equal((await first.request.post(base+'/api/auth/login',{data:login})).status(),200);
  const tow = await (await first.request.post(base+'/api/tows',{data:{airline:'MX',tailNumber:'NEDITOR',gate:'Gate 12',towSpot:'NL614',driver:'Editor Test',aircraftType:'A220'}})).json();
  towId = tow.id;
  const blank = await first.request.get(`${base}/api/tows/${towId}/tow-checklist.pdf`);
  assert.equal(blank.status(), 200);
  await fs.writeFile('tmp/pdf-review/blank-saved-paper.pdf',await blank.body());
  const page = await first.newPage(); const errors=[];
  page.on('pageerror',(error)=>errors.push(error.message));
  await page.goto(base);
  await page.getByText('v3.0.0',{exact:true}).waitFor();
  for (const viewport of [{width:1440,height:1050},{width:390,height:844}]) {
    await page.setViewportSize(viewport);
    const label = await page.locator('.app-version').boundingBox();
    assert.ok(label.x < 30 && label.y + label.height <= viewport.height && label.y > viewport.height - 60);
    await page.screenshot({path:`tmp/pdf-review/version-${viewport.width}.png`,fullPage:true});
  }
  await page.setViewportSize({width:1440,height:1050});
  await page.getByRole('button',{name:/NEDITOR/}).click();
  for (const name of ['Edit Tow Paper', 'Checklist PDF', 'Preview PDF']) assert.equal(await page.getByRole('link',{name,exact:true}).count(),1);
  await page.getByRole('link',{name:'Edit Tow Paper',exact:true}).click();
  await page.waitForFunction(()=>!globalThis.document.getElementById('save').disabled);
  for (const name of ['Save Draft','Reload Saved Draft','Download PDF']) {
    assert.equal(await page.getByRole('button',{name,exact:true}).count(),0);
  }
  assert.equal(await page.getByLabel('Aircraft Reg',{exact:true}).inputValue(),'NEDITOR');
  assert.equal(await page.getByLabel('Tractor Driver',{exact:true}).inputValue(),'Editor Test');
  assert.equal(await page.getByLabel('Tow from',{exact:true}).inputValue(),'Gate 12');
  assert.equal(await page.getByLabel('Tow to',{exact:true}).inputValue(),'NL614');
  await page.getByLabel('Aircraft Reg',{exact:true}).fill('NMANUAL');
  await page.getByRole('button',{name:'TTWS & Preparation',exact:true}).click();
  await page.getByRole('button',{name:'Checklist item 1: no',exact:true}).click();
  await page.getByLabel('Checklist item 1 exception comment',{exact:true}).fill('Shared comment test');
  await page.getByText('Shared draft saved / available to other signed-in users',{exact:true}).waitFor();
  const preview = await first.request.get(`${base}/api/tows/${towId}/tow-checklist.pdf?preview=true`);
  assert.equal(preview.status(),200);
  assert.match(preview.headers()['content-disposition'],/^inline/);
  assert.equal(preview.headers()['cache-control'],'private, no-store');
  await fs.writeFile('tmp/pdf-review/server-preview.pdf',await preview.body());
  const downloadResponse = await first.request.get(`${base}/api/tows/${towId}/tow-checklist.pdf`);
  assert.match(downloadResponse.headers()['content-disposition'],/^attachment/);
  await fs.writeFile('tmp/pdf-review/server-download.pdf',await downloadResponse.body());
  const second = await browser.newContext();
  await second.request.post(base+'/api/auth/login',{data:login});
  const viewer = await second.newPage();
  await viewer.goto(`${base}/api/paper-editor/?tow=${towId}`);
  await viewer.waitForFunction(()=>!globalThis.document.getElementById('save').disabled);
  await viewer.getByRole('button',{name:'TTWS & Preparation',exact:true}).click();
  assert.equal(await viewer.getByLabel('Checklist item 1 exception comment',{exact:true}).inputValue(),'Shared comment test');
  assert.equal(await viewer.getByRole('button',{name:'Checklist item 1: no',exact:true}).getAttribute('aria-pressed'),'true');
  await viewer.getByLabel('Checklist item 1 exception comment',{exact:true}).fill('Autosaved menu test');
  await viewer.getByRole('link',{name:'Menu',exact:true}).click();
  await viewer.getByRole('link',{name:'Edit Tow Paper',exact:true}).waitFor();
  assert.equal(await viewer.getByLabel('Aircraft Reg',{exact:true}).inputValue(),'NEDITOR');
  const menuSaved = await (await second.request.get(`${base}/api/tows/${towId}/paper-draft`)).json();
  assert.equal(menuSaved.state.text.undefined_2,'Autosaved menu test');
  await viewer.getByRole('link',{name:'Edit Tow Paper',exact:true}).click();
  await viewer.waitForFunction(()=>!globalThis.document.getElementById('save').disabled);
  await viewer.getByRole('button',{name:'TTWS & Preparation',exact:true}).click();
  const currentPdf = await second.request.get(`${base}/api/tows/${towId}/tow-checklist.pdf`);
  assert.equal(currentPdf.status(),200);
  await fs.writeFile('tmp/pdf-review/connected-export.pdf',await currentPdf.body());
  await viewer.screenshot({path:'tmp/pdf-review/connected-desktop.png',fullPage:true});
  await viewer.setViewportSize({width:390,height:844});
  await viewer.screenshot({path:'tmp/pdf-review/connected-mobile.png',fullPage:true});
  assert.equal(await viewer.evaluate(()=>globalThis.document.documentElement.scrollWidth<=globalThis.innerWidth),true);
  await page.getByLabel('Checklist item 1 exception comment',{exact:true}).fill('Stale edit must not overwrite');
  await page.getByText(/Draft not saved: Another user updated this paper/).waitFor();
  await page.getByRole('link',{name:'Menu',exact:true}).click();
  assert.match(page.url(),/\/api\/paper-editor/);
  const protectedDraft = await (await first.request.get(`${base}/api/tows/${towId}/paper-draft`)).json();
  assert.equal(protectedDraft.state.text.undefined_2,'Autosaved menu test');
  assert.equal((await first.request.put(`${base}/api/tows/${towId}`,{data:{aircraftType:'A320'}})).status(),200);
  page.once('dialog',dialog=>dialog.accept());
  await page.reload();
  await page.getByRole('button',{name:'TTWS & Preparation',exact:true}).click();
  await page.waitForFunction(()=>!globalThis.document.getElementById('save').disabled);
  assert.equal(await page.getByLabel('Checklist item 1 exception comment',{exact:true}).inputValue(),'Autosaved menu test');
  await page.getByLabel('TTWS tester full name and time',{exact:true}).fill('Tester preserved');
  await page.getByRole('button',{name:'Details & Risk',exact:true}).click();
  assert.equal(await page.getByLabel('Aircraft Type',{exact:true}).inputValue(),'A320');
  await page.getByLabel('Tractor Driver',{exact:true}).fill('Driver preserved');
  await page.getByLabel('Wing Walker LH',{exact:true}).fill('Walker preserved');
  await page.getByRole('button',{name:'Tow from: red',exact:true}).click();
  await page.getByRole('button',{name:'Final agreed status: green',exact:true}).click();
  await page.getByText('Shared draft saved / available to other signed-in users',{exact:true}).waitFor();
  page.once('dialog',dialog=>dialog.dismiss());
  await page.getByRole('button',{name:'Reset',exact:true}).click();
  assert.equal(await page.getByRole('button',{name:'Tow from: red',exact:true}).getAttribute('aria-pressed'),'true');
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'Reset',exact:true}).click();
  await page.getByText('Shared draft saved / available to other signed-in users',{exact:true}).waitFor();
  const resetDraft = await (await first.request.get(`${base}/api/tows/${towId}/paper-draft`)).json();
  assert.deepEqual(resetDraft.state.answers,{}); assert.deepEqual(resetDraft.state.risk,{});
  assert.equal(resetDraft.state.text['Aircraft Reg'],'NMANUAL');
  assert.equal(resetDraft.state.text['Tractor Driver'],'Driver preserved');
  assert.equal(resetDraft.state.text['Wing Walker LH'],'Walker preserved');
  assert.equal(resetDraft.state.text['Full Name'],'Tester preserved');
  assert.equal(resetDraft.state.text.undefined_2,undefined);
  await page.reload(); await page.waitForFunction(()=>!globalThis.document.getElementById('save').disabled);
  assert.equal(await page.getByLabel('Tractor Driver',{exact:true}).inputValue(),'Driver preserved');
  for (const viewport of [{width:1440,height:1050},{width:390,height:844}]) {
    await page.setViewportSize(viewport);
    await page.locator('#zoom').selectOption('1.25');
    await page.locator('#paper-scroll').hover(); await page.mouse.wheel(0,450);
    await page.waitForFunction(()=>globalThis.document.getElementById('paper-scroll').scrollTop>0);
    assert.equal(await page.evaluate(()=>globalThis.document.documentElement.scrollWidth<=globalThis.innerWidth),true);
    assert.equal(await page.getByRole('button',{name:'Reset',exact:true}).isVisible(),true);
    await page.screenshot({path:`tmp/pdf-review/editor-scroll-reset-${viewport.width}.png`,fullPage:true});
  }
  await page.setViewportSize({width:1440,height:1050});
  await first.request.post(`${base}/api/tows/${towId}/steps/towCompletedAt`,{data:{}});
  await page.goto(base);
  await page.getByRole('button',{name:/NEDITOR/}).click();
  await page.getByRole('link',{name:'Edit Tow Paper',exact:true}).waitFor();
  const continueButton = page.getByRole('button',{name:'Save and Continue',exact:true});
  if (await continueButton.count()) await continueButton.click();
  for (const name of ['Edit Tow Paper', 'Checklist PDF', 'Preview PDF']) assert.equal(await page.getByRole('link',{name,exact:true}).count(),1);
  assert.equal(await page.getByRole('link',{name:'Edit Tow Paper',exact:true}).evaluate((element)=>element.parentElement.classList.contains('page-actions')),true);
  await page.screenshot({path:'tmp/pdf-review/paper-action-bar.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Autosave, Menu return, shared drafts, PDF download, selective reset, and desktop/mobile paper scrolling passed.');
} finally {
  if (towId) {
    await first.request.delete(`${base}/api/tows/${towId}`,{data:{reason:'Editor integration regression test cleanup'}});
    await first.request.delete(`${base}/api/tows/${towId}/permanent`);
  }
  await browser.close();
}
